#!/usr/bin/env python3
"""Simple AH price updater for Linux (WoW running through Wine, Lutris, Steam/Proton, Bottles, ...).

Keeps Interface/AddOns/SimpleAH/PriceData.lua up to date with the hourly
auction house snapshot. Only needs python3, no extra packages.

    python3 simple-ah.py install [WOW_FOLDER]   set up and start the background updater
    python3 simple-ah.py status                 show what it is doing
    python3 simple-ah.py update                 download the newest prices once
    python3 simple-ah.py uninstall              stop and remove the background updater

WOW_FOLDER is only needed when the script can't find your game: the folder
that contains _forever_ (or the _forever_ folder itself).
"""

import fcntl
import glob
import json
import os
import shutil
import subprocess
import sys
import time
import urllib.error
import urllib.request

DATA_URL = "https://raw.githubusercontent.com/mkborik-cloud/forever-prices/data/prices.lua"
STATUS_URL = "https://raw.githubusercontent.com/mkborik-cloud/forever-prices/data/status.json"
USER_AGENT = "SimpleAH-Client-Linux/1.0"
HEADER = b"-- Generated by Simple AH"

SNAPSHOT_EVERY = 60 * 60  # Blizzard publishes auction data hourly
PUBLISH_LAG = 5 * 60      # first look 65 min after a snapshot
LATE_POLL = 5 * 60        # snapshot overdue: look again this often (status.json is ~2 KB)
RETRY_AFTER = 2 * 60      # network not up yet, GitHub hiccup

DATA_HOME = os.environ.get("XDG_DATA_HOME") or os.path.expanduser("~/.local/share")
CONFIG_HOME = os.environ.get("XDG_CONFIG_HOME") or os.path.expanduser("~/.config")
APP_DIR = os.path.join(DATA_HOME, "simple-ah")
INSTALLED = os.path.join(APP_DIR, "simple-ah.py")
STATE_PATH = os.path.join(APP_DIR, "state.json")
LOG_PATH = os.path.join(APP_DIR, "log.txt")
LOCK_PATH = os.path.join(APP_DIR, "lock")
SERVICE_NAME = "simple-ah.service"
SERVICE_PATH = os.path.join(CONFIG_HOME, "systemd", "user", SERVICE_NAME)
AUTOSTART_PATH = os.path.join(CONFIG_HOME, "autostart", "simple-ah.desktop")


# ---------------------------------------------------------------------------
# Small helpers
# ---------------------------------------------------------------------------

def log(msg):
    line = f"{time.strftime('%Y-%m-%d %H:%M:%S')}  {msg}"
    print(line, flush=True)
    try:
        os.makedirs(APP_DIR, exist_ok=True)
        if os.path.exists(LOG_PATH) and os.path.getsize(LOG_PATH) > 200_000:
            os.replace(LOG_PATH, LOG_PATH + ".old")
        with open(LOG_PATH, "a", encoding="utf-8") as f:
            f.write(line + "\n")
    except OSError:
        pass


def read_state():
    try:
        with open(STATE_PATH, encoding="utf-8") as f:
            return json.load(f)
    except (OSError, ValueError):
        return {}


def write_state(**updates):
    state = read_state()
    state.update(updates)
    os.makedirs(APP_DIR, exist_ok=True)
    tmp = STATE_PATH + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(state, f, indent=1)
    os.replace(tmp, STATE_PATH)


def child_ci(parent, name):
    """parent/name, matching the name case-insensitively (Wine folders are not always cased the same)."""
    exact = os.path.join(parent, name)
    if os.path.exists(exact):
        return exact
    try:
        for entry in os.listdir(parent):
            if entry.lower() == name.lower():
                return os.path.join(parent, entry)
    except OSError:
        pass
    return exact


def addon_dir(forever):
    return child_ci(child_ci(child_ci(forever, "Interface"), "AddOns"), "SimpleAH")


def addon_installed(forever):
    return os.path.isfile(os.path.join(addon_dir(forever), "SimpleAH.toc"))


def has_live_prices(forever):
    try:
        with open(os.path.join(addon_dir(forever), "PriceData.lua"), "rb") as f:
            return f.read(64).startswith(HEADER)
    except OSError:
        return False


# ---------------------------------------------------------------------------
# Finding the game
# ---------------------------------------------------------------------------

def normalize(path):
    """Accepts the _forever_ folder, the WoW folder above it, or anything inside _forever_."""
    path = os.path.abspath(os.path.expanduser(path))
    probe = path
    while probe and probe != os.path.dirname(probe):
        if os.path.basename(probe).lower() == "_forever_":
            return probe
        probe = os.path.dirname(probe)
    inner = child_ci(path, "_forever_")
    return inner if os.path.isdir(inner) else None


def wine_prefixes():
    home = os.path.expanduser("~")
    patterns = [
        os.path.join(home, ".wine"),
        os.path.join(home, ".wine*"),
        os.path.join(home, "Games", "*"),                       # Lutris default
        os.path.join(home, "Games", "*", "*"),
        os.path.join(home, ".local/share/lutris/runners/wine/*"),
        os.path.join(home, ".local/share/bottles/bottles/*"),    # Bottles
        os.path.join(home, ".var/app/com.usebottles.bottles/data/bottles/bottles/*"),
        os.path.join(home, ".steam/steam/steamapps/compatdata/*/pfx"),          # Steam / Proton
        os.path.join(home, ".local/share/Steam/steamapps/compatdata/*/pfx"),
        os.path.join(home, ".var/app/com.valvesoftware.Steam/data/Steam/steamapps/compatdata/*/pfx"),
        os.path.join(home, ".var/app/net.lutris.Lutris/data/lutris/prefixes/*"),
        os.path.join(home, "Faugus/*"),
    ]
    seen = []
    for p in patterns:
        for match in glob.glob(p):
            if os.path.isdir(os.path.join(match, "drive_c")) and match not in seen:
                seen.append(match)
    return seen


def find_forever():
    saved = read_state().get("wow")
    if saved and os.path.isdir(saved):
        return saved
    subs = ["Program Files (x86)/World of Warcraft", "Program Files/World of Warcraft",
            "World of Warcraft", "Games/World of Warcraft", "Battle.net/World of Warcraft"]
    for prefix in wine_prefixes():
        for sub in subs:
            hit = normalize(os.path.join(prefix, "drive_c", sub))
            if hit:
                return hit
    # WoW installed straight on a Linux drive
    for pattern in ["~/World of Warcraft", "~/Games/World of Warcraft", "/mnt/*/World of Warcraft",
                    "/mnt/*/Games/World of Warcraft", "/media/*/*/World of Warcraft",
                    "/run/media/*/*/World of Warcraft"]:
        for match in glob.glob(os.path.expanduser(pattern)):
            hit = normalize(match)
            if hit:
                return hit
    return None


# ---------------------------------------------------------------------------
# Prices
# ---------------------------------------------------------------------------

def fetch(url, timeout, extra_headers=None):
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT, **(extra_headers or {})})
    return urllib.request.urlopen(req, timeout=timeout)


def download_prices(forever):
    if not addon_installed(forever):
        raise FileNotFoundError(f"the SimpleAH addon is not in {os.path.dirname(addon_dir(forever))}")
    state = read_state()
    headers = {}
    if state.get("etag") and has_live_prices(forever):
        headers["If-None-Match"] = state["etag"]
    try:
        with fetch(DATA_URL, 60, headers) as resp:
            body = resp.read()
            etag = resp.headers.get("ETag", "")
    except urllib.error.HTTPError as e:
        if e.code == 304:
            return False
        raise
    if not body.startswith(HEADER):
        raise ValueError("downloaded file is not a price file")
    path = os.path.join(addon_dir(forever), "PriceData.lua")
    tmp = path + ".tmp"
    with open(tmp, "wb") as f:
        f.write(body)
    os.replace(tmp, path)
    write_state(etag=etag, updated=int(time.time()))
    log(f"prices updated ({len(body) // 1024} KB)")
    return True


def latest_snapshot():
    with fetch(STATUS_URL, 30) as resp:
        status = json.loads(resp.read())
    return max((int(m.get("scanned", 0)) for m in status.get("markets", [])), default=0) or int(status.get("updated", 0))


def next_wait(snapshot, now=None):
    now = time.time() if now is None else now
    due = snapshot + SNAPSHOT_EVERY + PUBLISH_LAG
    return int(min(max(due - now, LATE_POLL), SNAPSHOT_EVERY + PUBLISH_LAG))


def check_for_snapshot(forever):
    snapshot = latest_snapshot()
    have = int(read_state().get("snapshot", 0) or 0)
    if snapshot > have or not has_live_prices(forever):
        download_prices(forever)
        write_state(snapshot=snapshot)
        log(f"new snapshot from {time.strftime('%H:%M', time.localtime(snapshot))}")
    wait = next_wait(snapshot)
    log(f"next check in {wait // 60} min")
    return wait


# ---------------------------------------------------------------------------
# Background loop
# ---------------------------------------------------------------------------

def run():
    os.makedirs(APP_DIR, exist_ok=True)
    lock = open(LOCK_PATH, "w")
    try:
        fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
    except OSError:
        log("updater already running")
        return 0
    log("background updater started")
    while True:
        forever = find_forever()
        if not forever:
            log("WoW Forever not found, run: python3 simple-ah.py install /path/to/World of Warcraft")
            wait = 30 * 60
        else:
            try:
                wait = check_for_snapshot(forever)
            except Exception as e:  # network not up yet, GitHub hiccup, addon not copied yet
                log(f"update failed: {e}")
                wait = RETRY_AFTER
        # sleep by the wall clock in short steps so waking from suspend doesn't add delay
        deadline = time.time() + wait
        while time.time() < deadline:
            time.sleep(min(60, max(1, deadline - time.time())))


# ---------------------------------------------------------------------------
# Install / uninstall
# ---------------------------------------------------------------------------

def has_systemd():
    if not shutil.which("systemctl"):
        return False
    r = subprocess.run(["systemctl", "--user", "show-environment"], capture_output=True)
    return r.returncode == 0


def stop_running():
    if os.path.exists(SERVICE_PATH) and shutil.which("systemctl"):
        subprocess.run(["systemctl", "--user", "stop", SERVICE_NAME], capture_output=True)
    subprocess.run(["pkill", "-f", INSTALLED + " run"], capture_output=True)


def install(path_arg=None):
    if path_arg:
        forever = normalize(path_arg)
        if not forever:
            print(f"No _forever_ folder found in: {path_arg}")
            print("Give the World of Warcraft folder that contains _forever_.")
            return 1
    else:
        forever = find_forever()
        if not forever:
            print("Could not find WoW Forever. Run again with your World of Warcraft folder, e.g.:")
            print('  python3 simple-ah.py install "$HOME/Games/battlenet/drive_c/Program Files (x86)/World of Warcraft"')
            return 1
    print(f"WoW Forever: {forever}")
    if not addon_installed(forever):
        print(f"\nThe SimpleAH addon folder is missing. Copy the SimpleAH folder into:\n  {os.path.dirname(addon_dir(forever))}")
        print("and run this command again.")
        return 1
    write_state(wow=forever)

    stop_running()
    os.makedirs(APP_DIR, exist_ok=True)
    me = os.path.abspath(__file__)
    if me != INSTALLED:
        shutil.copyfile(me, INSTALLED)
    os.chmod(INSTALLED, 0o755)
    python = sys.executable or "/usr/bin/python3"

    try:
        check_for_snapshot(forever)
    except Exception as e:
        print(f"First download failed ({e}); the background updater will retry.")

    if has_systemd():
        os.makedirs(os.path.dirname(SERVICE_PATH), exist_ok=True)
        with open(SERVICE_PATH, "w", encoding="utf-8") as f:
            f.write(f"""[Unit]
Description=Simple AH price updater for WoW Forever
After=network-online.target

[Service]
ExecStart="{python}" "{INSTALLED}" run
Restart=always
RestartSec=60

[Install]
WantedBy=default.target
""")
        subprocess.run(["systemctl", "--user", "daemon-reload"], check=False)
        subprocess.run(["systemctl", "--user", "enable", "--now", SERVICE_NAME], check=False)
        print("\nDone. The updater runs in the background (systemd user service) and starts with your login.")
    else:
        os.makedirs(os.path.dirname(AUTOSTART_PATH), exist_ok=True)
        with open(AUTOSTART_PATH, "w", encoding="utf-8") as f:
            f.write(f"""[Desktop Entry]
Type=Application
Name=Simple AH updater
Exec="{python}" "{INSTALLED}" run
NoDisplay=true
X-GNOME-Autostart-enabled=true
""")
        subprocess.Popen([python, INSTALLED, "run"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                         start_new_session=True)
        print("\nDone. The updater runs in the background and starts when you log in to your desktop.")
    print("In game: /ah to search. After new prices arrive, /reload loads them.")
    return 0


def uninstall():
    stop_running()
    if os.path.exists(SERVICE_PATH):
        subprocess.run(["systemctl", "--user", "disable", SERVICE_NAME], capture_output=True)
        os.remove(SERVICE_PATH)
        subprocess.run(["systemctl", "--user", "daemon-reload"], capture_output=True)
    if os.path.exists(AUTOSTART_PATH):
        os.remove(AUTOSTART_PATH)
    shutil.rmtree(APP_DIR, ignore_errors=True)
    print("Simple AH updater removed. Delete Interface/AddOns/SimpleAH yourself if you want the addon gone too.")
    return 0


def status():
    state = read_state()
    forever = state.get("wow") or find_forever()
    print(f"WoW Forever:  {forever or 'not found'}")
    if forever:
        print(f"Addon:        {'installed' if addon_installed(forever) else 'MISSING'} ({addon_dir(forever)})")
    if state.get("snapshot"):
        print(f"Prices from:  {time.strftime('%Y-%m-%d %H:%M', time.localtime(int(state['snapshot'])))}")
    if os.path.exists(SERVICE_PATH):
        r = subprocess.run(["systemctl", "--user", "is-active", SERVICE_NAME], capture_output=True, text=True)
        print(f"Updater:      systemd service, {r.stdout.strip() or 'unknown'}")
    elif os.path.exists(AUTOSTART_PATH):
        print("Updater:      desktop autostart")
    else:
        print("Updater:      not installed (run: python3 simple-ah.py install)")
    try:
        with open(LOG_PATH, encoding="utf-8") as f:
            print("\nLast log lines:")
            for line in f.readlines()[-5:]:
                print("  " + line.rstrip())
    except OSError:
        pass
    return 0


def update_once():
    forever = find_forever()
    if not forever:
        print("WoW Forever not found; run install with your WoW folder first.")
        return 1
    check_for_snapshot(forever)
    return 0


def main(argv):
    cmd = argv[1] if len(argv) > 1 else "help"
    if cmd == "install":
        return install(argv[2] if len(argv) > 2 else None)
    if cmd == "run":
        return run()
    if cmd == "update":
        return update_once()
    if cmd == "status":
        return status()
    if cmd == "uninstall":
        return uninstall()
    print(__doc__)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
